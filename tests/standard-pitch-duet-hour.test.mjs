import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {readFileSync} from 'node:fs'
const pricing=createRequire(import.meta.url)('../js/package-pricing.js')
const wizard=readFileSync(new URL('../js/booking-wizard.js',import.meta.url),'utf8')
const feature=key=>pricing.features(pricing.packages[key]).join('\n')
assert.equal(pricing.packages.A.price,90000)
assert.equal(pricing.packages.A.title,'50분 녹음에 정밀 믹싱·마스터링이 필요하다면?')
assert.equal(pricing.packages.B.title,'녹음부터 정밀 믹싱·마스터링까지 한 번에 해결하고 싶다면?')
assert.equal(pricing.packages.C.title,'넉넉한 녹음 시간에 완성도 높은 패키지를 원한다면?')
assert.equal(pricing.packages.D.title,'두 사람이 함께 특별한 축가를 완성하고 싶다면?')
assert.match(pricing.selectionDetails('B'),/개별 옵션 추가보다 패키지로 40,000원 저렴하게!/)
assert.match(pricing.selectionDetails('C'),/개별 옵션 추가보다 패키지로 50,000원 저렴하게!/)
assert.match(pricing.selectionDetails('D'),/개별 옵션 추가보다 패키지로 60,000원 저렴하게!/)
assert.doesNotMatch(pricing.selectionDetails('A'),/저렴하게!/)
assert.equal(pricing.packages.A.delivery,'녹음일 기준 7일 이내 전달')
assert.equal(pricing.packages.B.price,170000)
assert.equal(pricing.packages.C.price,220000)
assert.equal(pricing.packages.D.price,240000)
assert.match(feature('A'),/음정·박자 보정 : 미포함/)
assert.match(feature('A'),/믹싱 : 정밀 믹싱 포함/)
assert.match(feature('A'),/마스터링 : 포함/)
assert.match(feature('A'),/디렉팅 : 1:1 맞춤 디렉팅/)
assert.match(feature('A'),/전달 : 녹음일 기준 7일 이내/)
assert.match(feature('B'),/음정·박자 보정 : 포함/)
assert.match(feature('B'),/믹싱 : 정밀 믹싱 포함/)
assert.match(feature('D'),/음정·박자 보정 : 포함/)
assert.match(pricing.cards('A').replace(/<[^>]+>/g,' '),/50분 녹음과 정밀 믹싱·마스터링이 필요하다면\? 기본에 충실한 스탠다드를 추천드려요!/)
assert.match(pricing.cards('A'),/90,000원/)
assert.equal(pricing.options.find(o=>o.key==='tuning').label,'음정·박자 보정')
const plain=pricing.quote({package:'A'})
const withTuning=pricing.quote({package:'A',tuning:'1'})
assert.equal(plain.total,90000)
assert.equal(withTuning.total,130000)
assert.equal(withTuning.minutes,50)
assert.equal(withTuning.delivery,'녹음일 기준 7일 이내 전달')
assert.equal(withTuning.options.some(o=>o.key==='tuning'),true)
const duet=pricing.quote({package:'D',extraHour:'1'})
assert.equal(duet.total,300000)
assert.equal(duet.minutes,210)
assert.equal(duet.options.find(o=>o.key==='extraHour').label,'녹음 1시간 추가')
assert.equal(pricing.quote({package:'D'}).total,240000)
assert.equal(pricing.quote({package:'B',extraHour:'1'}).total,230000)
assert.match(wizard,/const included=\['1:1 디렉팅',\.\.\.\(q\.package\.tuning\?\['음정·박자 보정'\]:\[\]\)/)
assert.match(wizard,/key==='tuning'\?!!q\.package\.tuning/)
assert.match(wizard,/key==='detailMix'\|\|key==='precisionMix'\)\?!!q\.package\.mixing:false/)
console.log('standard mix without pitch, 7-day delivery, duet extra hour passed')
