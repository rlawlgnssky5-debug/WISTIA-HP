import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {readFileSync} from 'node:fs'
const pricing=createRequire(import.meta.url)('../js/package-pricing.js')
const wizard=readFileSync(new URL('../js/booking-wizard.js',import.meta.url),'utf8')
const feature=key=>pricing.features(pricing.packages[key]).join('\n')
assert.equal(pricing.packages.A.price,90000)
assert.equal(pricing.packages.A.title,'녹음 + 음정·박자 보정!')
assert.equal(pricing.packages.A.delivery,'당일 음원 전달')
assert.equal(pricing.packages.B.price,170000)
assert.equal(pricing.packages.C.price,220000)
assert.equal(pricing.packages.D.price,240000)
assert.match(feature('A'),/음정·박자 보정 : 포함/)
assert.match(feature('A'),/믹싱 : 기본 믹싱/)
assert.match(feature('A'),/마스터링 : 미포함/)
assert.match(feature('A'),/디렉팅 : 1:1 맞춤 디렉팅/)
assert.match(feature('A'),/전달 : 당일/)
assert.match(feature('B'),/음정·박자 보정 : 포함/)
assert.match(feature('B'),/믹싱 : 정밀 믹싱 포함/)
assert.match(feature('D'),/음정·박자 보정 : 포함/)
assert.match(pricing.cards('A').replace(/<[^>]+>/g,' '),/녹음 \+ 음정·박자 보정/)
assert.match(pricing.cards('A'),/90,000원/)
assert.equal(pricing.options.find(o=>o.key==='tuning').label,'음정·박자 보정')
const plain=pricing.quote({package:'A'})
const withTuning=pricing.quote({package:'A',tuning:'1'})
assert.equal(plain.total,90000)
assert.equal(withTuning.total,90000)
assert.equal(withTuning.minutes,50)
assert.equal(withTuning.delivery,'당일 음원 전달')
assert.equal(withTuning.options.some(o=>o.key==='tuning'),false)
const duet=pricing.quote({package:'D',extraHour:'1'})
assert.equal(duet.total,300000)
assert.equal(duet.minutes,210)
assert.equal(duet.options.find(o=>o.key==='extraHour').label,'녹음 1시간 추가')
assert.equal(pricing.quote({package:'D'}).total,240000)
assert.equal(pricing.quote({package:'B',extraHour:'1'}).total,230000)
assert.match(wizard,/const included=\['1:1 디렉팅','음정·박자 보정'/)
assert.match(wizard,/key==='tuning'\?q\.package\.tuning\|\|q\.package\.key==='A'/)
assert.match(wizard,/key==='detailMix'\|\|key==='precisionMix'\?q\.package\.mixing:false/)
console.log('standard pitch check, 90000 same-day, renamed option, duet extra hour passed')
