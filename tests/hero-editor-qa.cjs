const assert = require('node:assert/strict')
const {chromium} = require(process.env.WISTIA_NODE_MODULES + '/playwright')

;(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'})
  try {
    const page = await browser.newPage({viewport:{width:1440,height:900}})
    await page.goto('http://127.0.0.1:4173/?v=115#/detail/wedding')
    assert.equal(await page.locator('#heroEditorLaunch').count(),1)
    await page.locator('#heroEditorLaunch').click()
    await page.locator('#heroEditorCanvas').waitFor()
    if (process.env.WISTIA_EDITOR_SCREENSHOT) await page.screenshot({path:process.env.WISTIA_EDITOR_SCREENSHOT})
    assert.match(page.url(),/edit=1/)
    assert.equal(await page.locator('.hero-edit-block').count(),7)
    await page.locator('[data-block-id="title"]').click()
    await page.locator('[data-block-id="title"] [data-editor-action="text"]').click()
    await page.locator('[data-block-id="title"] .hero-edit-content').fill('새 식전 영상 제목')
    await page.locator('.hero-editor-bar').click()
    const leftBefore = await page.locator('[data-block-id="title"]').evaluate(el => parseFloat(el.style.left))
    const move = await page.locator('[data-block-id="title"] [data-editor-action="move"]').boundingBox()
    await page.mouse.move(move.x + move.width/2, move.y + move.height/2)
    await page.mouse.down()
    await page.mouse.move(move.x + move.width/2 + 70, move.y + move.height/2 + 25, {steps:5})
    await page.mouse.up()
    const leftAfter = await page.locator('[data-block-id="title"]').evaluate(el => parseFloat(el.style.left))
    assert.ok(leftAfter > leftBefore,'title can be dragged')
    const widthBefore = await page.locator('[data-block-id="title"]').evaluate(el => parseFloat(el.style.width))
    const resize = await page.locator('[data-block-id="title"] [data-editor-action="resize"]').boundingBox()
    await page.mouse.move(resize.x + resize.width/2, resize.y + resize.height/2)
    await page.mouse.down()
    await page.mouse.move(resize.x + resize.width/2 + 60, resize.y + resize.height/2 + 30, {steps:5})
    await page.mouse.up()
    const widthAfter = await page.locator('[data-block-id="title"]').evaluate(el => parseFloat(el.style.width))
    assert.ok(widthAfter > widthBefore,'title can be resized')
    await page.locator('[data-block-id="intro"]').click()
    await page.locator('[data-block-id="intro"] [data-editor-action="delete"]').click()
    assert.equal(await page.locator('[data-block-id="intro"]').count(),0,'removed block is hidden')
    await page.locator('#heroEditorHidden button').click()
    assert.equal(await page.locator('[data-block-id="intro"]').count(),1,'removed block can be restored')
    await page.reload()
    assert.equal(await page.locator('[data-block-id="title"] .hero-edit-content').textContent(),'새 식전 영상 제목','draft survives reload')
    await page.locator('.hero-editor-actions a').click()
    assert.equal(await page.locator('.detail-hero h1').textContent(),'듀엣 식전 영상','public page copy remains unchanged')
    console.log('hero editor: edit, drag, resize, hide/restore, reload, public isolation passed')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
