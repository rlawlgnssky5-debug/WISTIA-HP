const {test}=require('node:test')
const assert=require('node:assert/strict')
const path=require('node:path')
const fs=require('node:fs')
const origin=process.env.WISTIA_TEST_ORIGIN||'http://127.0.0.1:4186'
const evidence=path.resolve('_codex_ref/qa2/round2')
fs.mkdirSync(evidence,{recursive:true})
test('round 2: responsive controls, intro, lazy calendars and chat collisions',{skip:!process.env.WISTIA_TEST_BROWSER&&!process.env.WISTIA_TEST_CDP},async()=>{
 const {chromium}=require(process.env.PLAYWRIGHT_CORE_PATH||'playwright-core')
 const browser=process.env.WISTIA_TEST_CDP?await chromium.connectOverCDP(process.env.WISTIA_TEST_CDP):await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--autoplay-policy=no-user-gesture-required']})
 try{
 for(const width of [360,375,390,1280]){
  const context=await browser.newContext({viewport:{width,height:900}})
  const page=await context.newPage(),errors=[],requests=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(r.url().includes('/api/availability'))requests.push(r.url())})
  for(const product of ['solo','duo']){
   await page.goto(origin+'/detail/'+product,{waitUntil:'domcontentloaded'})
   await page.locator('.wistia-intro').waitFor()
   assert.deepEqual(await page.locator('.wistia-intro').evaluate(e=>{const b=e.getBoundingClientRect();return [getComputedStyle(e).position,b.width,b.height]}),['fixed',width,900])
   if(product==='solo')await page.screenshot({path:path.join(evidence,`intro-${width}.png`)})
   await page.locator('.wistia-intro').waitFor({state:'detached'})
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
   assert.equal(await page.locator('.solo-selection-title').isVisible(),false)
   await page.locator('.solo-shot-top').screenshot({path:path.join(evidence,`top-${product}-${width}.png`)})
   const chat=page.locator('#floatingKakaoChat')
   assert.equal(await chat.getAttribute('href'),'https://pf.kakao.com/_GbExjX/chat')
   assert.equal(await chat.evaluate(e=>e.getBoundingClientRect().width),52)
   await page.locator('#soloPoint04').scrollIntoViewIfNeeded()
   await page.waitForTimeout(200)
   assert.equal(await chat.evaluate(e=>{const a=e.getBoundingClientRect(),b=document.querySelector('.solo-footer-inquiry').getBoundingClientRect();return !(a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top)||getComputedStyle(e).opacity==='0'}),true)
   for(const ratio of [30,50,70,100]){
    await page.locator(`[data-solo-ratio="${ratio}"]`).click()
    await page.waitForFunction(()=>{const a=document.querySelector('[data-solo-audio]');return !a.paused&&a.currentTime>0})
    assert.equal(await page.locator('[data-solo-state]').innerText(),'재생 중')
    assert.equal(await page.locator('[data-solo-mix]').innerText(),`AR ${ratio}%`)
    assert.equal(await page.locator(`[data-solo-ratio="${ratio}"]`).getAttribute('aria-pressed'),'true')
   }
   await page.locator('[data-solo-ratio="50"]').click()
   await page.waitForFunction(()=>document.querySelector('[data-solo-audio]').duration>0)
   assert.notEqual(await page.locator('[data-solo-duration]').innerText(),'0:00')
   await page.locator('.solo-p4-seek').focus()
   const before=await page.locator('.solo-p4-seek').inputValue()
   await page.waitForTimeout(700)
   assert.ok(Number(await page.locator('.solo-p4-seek').inputValue())>Number(before))
   await page.locator('.solo-p4-seek').evaluate(e=>{e.value='42';e.dispatchEvent(new Event('input',{bubbles:true}))})
   assert.match(await page.locator('[data-solo-current]').innerText(),/0:42/)
   await page.locator('#soloPoint04').screenshot({path:path.join(evidence,`point04-${product}-${width}.png`)})
   await page.locator('.solo-p4-stop').click()
   assert.equal(await page.locator('[data-solo-audio]').evaluate(e=>e.paused&&e.currentTime===0),true)
   assert.equal(await page.locator('[data-solo-state]').innerText(),'재생 대기')
   await page.locator('.solo-footer-inquiry').scrollIntoViewIfNeeded()
   await page.waitForTimeout(200)
   assert.equal(await chat.evaluate(e=>getComputedStyle(e).opacity),'0')
  }
  requests.length=0
  await page.goto(origin+'/event/solo',{waitUntil:'networkidle'})
  assert.equal(requests.length,0,'No availability lookup on page load')
  await page.locator('[data-calendar-trigger="eventDate"]').click()
  const cal=page.locator('[data-calendar="eventDate"]')
  assert.equal(await cal.locator('[data-calendar-close]').innerText(),'× 닫기')
  await cal.locator('[data-calendar-day]:not([disabled])').first().click()
  assert.equal(await cal.locator('[data-calendar-close]').innerText(),'확인')
  const selected=await page.locator('#contact-eventDate').inputValue()
  await cal.locator('[data-calendar-close]').click()
  assert.equal(await cal.isVisible(),false)
  assert.equal(await page.locator('#contact-eventDate').inputValue(),selected)
  await page.locator('[data-calendar-trigger="bookingDate"]').click()
  await page.waitForFunction(()=>document.querySelector('[data-calendar="bookingDate"] [data-calendar-day]:not([disabled])'))
  assert.ok(requests.length>0)
  await page.locator('[data-calendar="bookingDate"] [data-calendar-day]:not([disabled])').first().click()
  await page.waitForFunction(()=>document.querySelector('#contactInquiryForm').dataset.scheduleState==='ready')
  assert.deepEqual(errors,[])
  await context.close()
 }
 // A failing production-shaped response is rendered as the Kakao fallback, with no unhandled JS error.
 const context=await browser.newContext({viewport:{width:390,height:900},reducedMotion:'reduce'}),page=await context.newPage(),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/api/availability?*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({ok:false})}))
 await page.goto(origin+'/event/solo',{waitUntil:'networkidle'})
 await page.locator('[data-calendar-trigger="bookingDate"]').click()
 await page.waitForFunction(()=>document.querySelector('[data-calendar-range-status]').textContent.includes('카카오톡 확인 필요'))
 assert.deepEqual(errors,[])
 await context.close()
 }finally{await browser.close()}
})
