const assert = require('node:assert/strict')
const {chromium} = require(process.env.WISTIA_NODE_MODULES + '/playwright')

;(async () => {
  const browser = await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'})
  try {
    const page = await browser.newPage({viewport:{width:1293,height:911}})
    await page.goto('http://127.0.0.1:4173/?v=116&edit=1#/detail/wedding')
    assert.equal(await page.locator('#processEditorBar').count(), 1)
    await page.locator('#process .section-heading h2').click()
    await page.locator('[data-process-action=text]').click()
    await page.locator('#process .section-heading h2').fill('새 진행 제목')
    await page.locator('#process .section-heading p').click()
    assert.equal(await page.locator('#process .section-heading h2').textContent(), '새 진행 제목')
    await page.locator('[data-process-format=live]').click()
    assert.equal(await page.locator('#processTypeLive').isVisible(), true)
    await page.locator('#processTypeLive h3').first().click()
    await page.locator('[data-process-action=text]').click()
    await page.locator('#processTypeLive h3').first().fill('새 첫 단계')
    await page.locator('#process .section-heading h2').click()
    await page.reload()
    assert.equal(await page.locator('#process .section-heading h2').textContent(), '새 진행 제목')
    await page.locator('[data-process-format=live]').click()
    assert.equal(await page.locator('#processTypeLive h3').first().textContent(), '새 첫 단계')
    await page.locator('#process .section-heading p').click()
    await page.locator('[data-process-action=delete]').click()
    assert.equal(await page.locator('#process .section-heading p').isVisible(), false)
    await page.locator('#processEditorRestore button').filter({hasText:'진행 과정 설명'}).click()
    assert.equal(await page.locator('#process .section-heading p').isVisible(), true)
    await page.goto('http://127.0.0.1:4173/?v=116#/detail/wedding')
    assert.equal(await page.locator('#processEditorBar').count(), 0)
    assert.equal(await page.locator('#process .section-heading h2').textContent(), '진행 과정')
    console.log('process editor QA passed')
  } finally { await browser.close() }
})().catch(err => {console.error(err);process.exitCode=1})
