const assert = require('node:assert/strict')
const {chromium} = require(process.env.WISTIA_NODE_MODULES + '/playwright')

;(async () => {
 const browser = await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'})
 try {
  for (const width of [390,1440]) {
   const page=await browser.newPage({viewport:{width,height:900}}),errors=[]
   page.on('pageerror',error=>errors.push(error.message))
   await page.goto('http://127.0.0.1:4173/?v=126#/')
   assert.equal(await page.locator('input[name=finderRole]').count(),3)
   assert.match(await page.locator('.finder-home').innerText(),/신랑 또는 신부예요.*축가를 부를 사람이에요.*프로포즈를 준비하고 있어요/s)
   const choiceBoxes=await page.locator('.finder-choice').evaluateAll(nodes=>nodes.map(node=>{const box=node.getBoundingClientRect();return{x:box.x,y:box.y,width:box.width,textAlign:getComputedStyle(node).textAlign}}))
   assert.ok(choiceBoxes.every((box,index)=>Math.abs(box.x-choiceBoxes[0].x)<1&&Math.abs(box.width-choiceBoxes[0].width)<1&&box.textAlign==='center'&&(index===0||box.y>choiceBoxes[index-1].y)),'all choices form one centered vertical column')
   assert.equal(await page.locator('.finder-intro').evaluate(node=>getComputedStyle(node).textAlign),'center')
   await page.locator('input[name=finderRole][value=couple]').locator('..').click()
   assert.match(page.url(),/#\/find\/service$/)
   await page.locator('input[name=finderMoment][value=pre]').locator('..').click()
   assert.match(page.url(),/#\/find\/people$/)
   assert.match(await page.locator('#finderTitle').textContent(),/혼자 준비하시나요, 두 분이 함께 준비하시나요/)
   await page.locator('.finder-back').click()
   assert.match(page.url(),/#\/find\/service$/)
   await page.locator('input[name=finderMoment][value=pre]').locator('..').click()
   assert.match(page.url(),/#\/find\/people$/)
   await page.locator('input[name=finderPeople][value=two]').locator('..').click()
   assert.match(page.url(),/#\/detail\/wedding$/)
   assert.match(await page.locator('h1').first().innerText(),/듀엣 식전 영상/)
   await page.locator('.wordmark').click()
   await page.locator('input[name=finderRole][value=singer]').locator('..').click()
   assert.match(page.url(),/#\/find\/lyrics$/)
   assert.match(await page.locator('#finderTitle').textContent(),/가사 영상도 필요하신가요/)
   await page.locator('input[name=finderLyrics][value=yes]').locator('..').click()
   assert.match(page.url(),/#\/ar\/friend$/)
   assert.match(await page.locator('.selected-song-result').innerText(),/선택한 구성.*가사 영상 포함.*\+40,000원/s)
   assert.equal(await page.locator('.selected-song-result img').count(),1)
   assert.doesNotMatch(await page.locator('main').innerText(),/인원 추가/)
   await page.goto('http://127.0.0.1:4173/?v=126#/event/solo/friend')
   assert.equal(await page.locator('input[data-song-option=lyrics]').isChecked(),true)
   await page.locator('.wordmark').click()
   await page.locator('input[name=finderRole][value=proposal]').locator('..').click()
   assert.match(page.url(),/#\/detail\/proposal$/)
   assert.equal(errors.length,0,errors.join('\n'))
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
   await page.close()
  }
  console.log('home finder QA passed')
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
