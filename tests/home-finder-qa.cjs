const assert = require('node:assert/strict')
const {chromium} = require(process.env.WISTIA_NODE_MODULES + '/playwright')

;(async () => {
 const browser = await chromium.launch({headless:true,executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe'})
 try {
  for (const width of [390,1440]) {
   const page=await browser.newPage({viewport:{width,height:900}}),errors=[]
   page.on('pageerror',error=>errors.push(error.message))
   await page.goto('http://127.0.0.1:4173/?v=126#/')
   const headerSurface=await page.locator('#siteHeader').evaluate(async node=>{window.scrollTo(0,300);window.dispatchEvent(new Event('scroll'));await new Promise(resolve=>requestAnimationFrame(resolve));return {background:getComputedStyle(node).backgroundColor,filter:getComputedStyle(node).backdropFilter}})
   assert.equal(headerSurface.background,'rgb(255, 255, 255)','sticky header should keep a fully opaque white surface')
   assert.equal(headerSurface.filter,'none','sticky header should not blur scrolling content behind it')
   assert.equal(await page.locator('input[name=finderRole]').count(),3)
   assert.match(await page.locator('.finder-home').innerText(),/사전 AR 축가.*식전 영상 \/ 축가 영상.*프로포즈/s)
   assert.equal(await page.locator('.finder-stage-role .finder-intro .eyebrow').count(),0,'intro service picker should not show a step number')
   assert.equal(await page.locator('.finder-service-badge').count(),2)
   assert.match(await page.locator('.finder-service-badge').first().innerText(),/음원/)
   assert.match(await page.locator('.finder-service-badge').nth(1).innerText(),/영상/)
   assert.equal(await page.locator('.finder-choice-mark').count(),3,'every service choice should retain the circular selector above its label')
   assert.equal(await page.locator('.finder-choice').first().evaluate(choice=>Boolean(choice.querySelector('.finder-choice-mark').compareDocumentPosition(choice.querySelector('.finder-service-badge')) & Node.DOCUMENT_POSITION_FOLLOWING)),true,'service badge should move into the title row below the circular selector')
   assert.equal(await page.locator('.finder-intro-splash').count(),1)
   assert.equal(await page.locator('.finder-intro-splash img').count(),1)
   await page.locator('.finder-intro-splash').waitFor({state:'hidden',timeout:4000})
   const introLayout=await page.locator('.finder-home').evaluate(root=>{const title=root.querySelector('#finderTitle').getBoundingClientRect(),box=root.getBoundingClientRect(),gradient=getComputedStyle(root,'::before');return{contained:title.left>=box.left&&title.right<=box.right+1,gradient:gradient.backgroundImage,contentAnimation:getComputedStyle(root.querySelector('.finder-content')).animationName}})
   assert.equal(introLayout.contained,true,'finder heading must stay inside the content width')
   assert.ok(await page.locator('.finder-stage-role .finder-intro h1').evaluate(node=>parseFloat(getComputedStyle(node).fontSize))<=44,'intro heading should not dominate the service choices')
   assert.match(introLayout.gradient,/radial-gradient/)
   assert.equal(introLayout.contentAnimation,'finder-content-rise')
   const choiceBoxes=await page.locator('.finder-choice').evaluateAll(nodes=>nodes.map(node=>{const box=node.getBoundingClientRect();return{x:box.x,y:box.y,width:box.width,textAlign:getComputedStyle(node).textAlign}}))
   assert.ok(choiceBoxes.every((box,index)=>Math.abs(box.x-choiceBoxes[0].x)<1&&Math.abs(box.width-choiceBoxes[0].width)<1&&box.textAlign==='center'&&(index===0||box.y>choiceBoxes[index-1].y)),'all choices form one centered vertical column')
   assert.equal(await page.locator('.finder-intro').evaluate(node=>getComputedStyle(node).textAlign),'center')
   await page.locator('input[name=finderRole][value=couple]').locator('..').click()
   assert.match(page.url(),/#\/detail\/solo-film\/making$/)
   await page.locator('.wordmark').click()
   await page.locator('input[name=finderRole][value=singer]').locator('..').click()
   assert.match(page.url(),/#\/detail\/solo$/)
   await page.locator('.wordmark').click()
   await page.locator('input[name=finderRole][value=proposal]').locator('..').click()
   assert.match(page.url(),/#\/detail\/proposal$/)
   assert.equal(errors.length,0,errors.join('\n'))
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
   await page.close()
  }
  console.log('home finder QA passed')
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
